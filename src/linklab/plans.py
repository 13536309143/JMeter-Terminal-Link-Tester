"""Compile declarative scenarios into editable JMeter 5.6 JMX files."""
from __future__ import annotations

import csv
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path


def prop(node, name, value):
    kind = "boolProp" if isinstance(value, bool) else "stringProp"
    ET.SubElement(node, kind, name=name).text = str(value).lower() if isinstance(value, bool) else str(value)


def element(parent, tag, gui, name, properties=None):
    node = ET.SubElement(parent, tag, guiclass=gui, testclass=tag, testname=name, enabled="true")
    for key, value in (properties or {}).items():
        prop(node, key, value)
    tree = ET.SubElement(parent, "hashTree")
    return node, tree


def script(parent, name, body, kind="JSR223Sampler"):
    node, tree = element(parent, kind, "TestBeanGUI", name,
                         {"scriptLanguage": "groovy", "parameters": "", "filename": "",
                          "cacheKey": "true", "script": body.strip()})
    return node, tree


def group(parent, name, threads, ramp, tag="ThreadGroup"):
    node, tree = element(parent, tag, "ThreadGroupGui", name,
                         {"ThreadGroup.on_sample_error": "continue", "ThreadGroup.num_threads": threads,
                          "ThreadGroup.ramp_time": ramp, "ThreadGroup.scheduler": False,
                          "ThreadGroup.same_user_on_next_iteration": True})
    controller = ET.SubElement(node, "elementProp", name="ThreadGroup.main_controller",
                               elementType="LoopController", guiclass="LoopControlPanel",
                               testclass="LoopController", testname="Loop")
    prop(controller, "LoopController.continue_forever", False)
    prop(controller, "LoopController.loops", 1)
    return tree


def connect(parent, scenario, name, client_id):
    v = scenario.values
    _, tree = element(parent, "net.xmeter.samplers.ConnectSampler", "net.xmeter.gui.ConnectSamplerUI", name,
                      {"mqtt.server": v["broker"]["host"], "mqtt.port": v["broker"]["port"],
                       "mqtt.protocol": "TCP", "mqtt.version": "3.1.1", "mqtt.client_name": "fusesource",
                       "mqtt.client_id_prefix": client_id, "mqtt.client_id_suffix": False,
                       "mqtt.conn_clean_session": "true", "mqtt.conn_keep_alive": v["mqtt"]["keepalive_seconds"],
                       "mqtt.conn_timeout": v["mqtt"]["connect_timeout_seconds"],
                       "mqtt.conn_attampt_max": "0", "mqtt.reconn_attampt_max": "0",
                       "mqtt.user_name": "", "mqtt.password": "", "mqtt.dual_ssl_authentication": False,
                       "mqtt.keystore_file_path": "", "mqtt.keystore_password": "",
                       "mqtt.clientcert_file_path": "", "mqtt.clientcert_password": ""})
    broker = v["broker"]
    if broker["username_env"]:
        script(tree, "读取环境变量中的认证信息", f"""
sampler.setUserNameAuth(System.getenv('{broker['username_env']}'))
sampler.setPasswordAuth(System.getenv('{broker['password_env']}'))
""", "JSR223PreProcessor")


def disconnect(parent, name):
    element(parent, "net.xmeter.samplers.DisConnectSampler", "net.xmeter.gui.DisConnectSamplerUI", name)


def compile_plan(scenario, output: Path, run_id: str):
    if not re.fullmatch(r"[a-f0-9]{16}", run_id):
        raise ValueError("run_id must be 16 lowercase hexadecimal characters")
    if scenario.values["protocol"] != "mqtt":
        from .network_plans import compile_network_plan
        return compile_network_plan(scenario, output, run_id)
    output.mkdir(parents=True, exist_ok=True)
    v = scenario.values
    devices = scenario.devices()
    csv_path = output / "devices.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=["device_id", "device_type", "site"])
        writer.writeheader()
        writer.writerows(devices)
    root = ET.Element("jmeterTestPlan", version="1.2", properties="5.0", jmeter="5.6.3")
    tree = ET.SubElement(root, "hashTree")
    plan, main = element(tree, "TestPlan", "TestPlanGui", f"LinkLab · {v['name']}",
                         {"TestPlan.comments": "Generated by LinkLab. Native EMQX MQTT samplers. Credentials are read from environment variables.",
                          "TestPlan.functional_mode": False, "TestPlan.serialize_threadgroups": False,
                          "TestPlan.tearDown_on_shutdown": True})
    args = ET.SubElement(plan, "elementProp", name="TestPlan.user_defined_variables", elementType="Arguments",
                         guiclass="ArgumentsPanel", testclass="Arguments", testname="Run variables")
    variables = ET.SubElement(args, "collectionProp", name="Arguments.arguments")
    topic_root = f"{v['mqtt']['topic_prefix']}/{run_id}/up"
    for key, value in {"ll_run_id": run_id, "ll_topic_root": topic_root}.items():
        argument = ET.SubElement(variables, "elementProp", name=key, elementType="Argument")
        for field, content in {"Argument.name": key, "Argument.value": value, "Argument.metadata": "="}.items():
            prop(argument, field, content)
    init = group(main, "初始化实验", 1, 0, "SetupThreadGroup")
    script(init, "初始化运行状态", """
props.put('ll.finished', new java.util.concurrent.atomic.AtomicInteger(0))
props.put('ll.observed', new java.util.concurrent.atomic.AtomicLong(0))
props.put('ll.ready', false)
props.put('ll.lastFinishNs', System.nanoTime())
SampleResult.setIgnore()
""")

    observer = group(main, "MQTT 订阅探针", 1, 0)
    connect(observer, scenario, "Observer Connect", f"o{run_id}")
    condition = (f"${{__groovy(props.get('ll.finished').get() < {v['load']['terminals']} || "
                 f"(System.nanoTime() - props.get('ll.lastFinishNs')) < {int(v['collection']['drain_seconds'] * 1e9)}L)}}")
    _, observer_loop = element(observer, "WhileController", "WhileControllerGui", "订阅并等待采集排空",
                               {"WhileController.condition": condition})
    _, sub_tree = element(observer_loop, "net.xmeter.samplers.SubSampler", "net.xmeter.gui.SubSamplerUI", "MQTT Subscribe",
                          {"mqtt.topic_name": "${ll_topic_root}/+", "mqtt.qos_level": v["mqtt"]["qos"],
                           "mqtt.add_timestamp": False, "mqtt.debug_response": False,
                           "mqtt.sample_condition": "specified elapsed time (ms)", "mqtt.sample_condition_value": "250"})
    script(sub_tree, "订阅就绪屏障与消息计数", f"""
if (prev.isSuccessful()) {{
    int received = prev.getSampleCount()
    props.get('ll.observed').addAndGet(received)
    if (!props.get('ll.ready')) {{
        // The native SubSampler has installed its listener. Confirm SUBACK before releasing publishers.
        def latch = new java.util.concurrent.CountDownLatch(1)
        def error = new java.util.concurrent.atomic.AtomicReference()
        def conn = vars.getObject('conn')
        conn.subscribe([vars.get('ll_topic_root') + '/+'] as String[],
            net.xmeter.samplers.mqtt.MQTTQoS.fromValue({v['mqtt']['qos']}),
            {{ latch.countDown() }} as Runnable,
            {{ Throwable e -> error.set(e); latch.countDown() }} as java.util.function.Consumer)
        if (!latch.await({v['mqtt']['connect_timeout_seconds']}, java.util.concurrent.TimeUnit.SECONDS) || error.get() != null) {{
            prev.setSuccessful(false)
            prev.setResponseMessage('Observer SUBACK readiness failed')
        }} else {{ props.put('ll.ready', true) }}
    }}
    // EMQX's batch count is a message count; persist one row per sampling window in JTL.
    prev.setSampleCount(1)
    if (received == 0 && prev.isSuccessful()) {{ prev.setIgnore() }}
}}
""", "JSR223PostProcessor")
    disconnect(observer, "Observer Disconnect")

    terminals = group(main, "参数化模拟终端", v["load"]["terminals"], v["load"]["ramp_up_seconds"])
    element(terminals, "CSVDataSet", "TestBeanGUI", "一线程一个终端",
            {"filename": str(csv_path.resolve()), "fileEncoding": "UTF-8", "variableNames": "",
             "ignoreFirstLine": False, "delimiter": ",", "quotedData": False,
             "recycle": False, "stopThread": True, "shareMode": "shareMode.all"})
    script(terminals, "等待订阅就绪", f"""
long deadline = System.nanoTime() + {v['mqtt']['connect_timeout_seconds'] + 10}L * 1000000000L
while (!props.get('ll.ready') && System.nanoTime() < deadline) {{ Thread.sleep(10) }}
if (!props.get('ll.ready')) {{
    SampleResult.setSuccessful(false)
    SampleResult.setResponseCode('504')
    SampleResult.setResponseMessage('MQTT observer readiness timeout')
}} else {{ SampleResult.setIgnore() }}
""")
    connect(terminals, scenario, "MQTT Connect", f"d{run_id[:8]}${{__threadNum}}")
    loop_node, loop = element(terminals, "LoopController", "LoopControlPanel", "定时上报",
                              {"LoopController.continue_forever": False,
                               "LoopController.loops": v["load"]["messages_per_terminal"]})
    _, pacing = script(loop, "终端上报节拍", "SampleResult.setIgnore()")
    element(pacing, "ConstantTimer", "ConstantTimerGui", "终端上报间隔",
            {"ConstantTimer.delay": v["load"]["interval_ms"]})
    _, pub_tree = element(loop, "net.xmeter.samplers.PubSampler", "net.xmeter.gui.PubSamplerUI", "MQTT Publish",
                          {"mqtt.topic_name": "${ll_topic_root}/${device_id}", "mqtt.qos_level": v["mqtt"]["qos"],
                           "mqtt.add_timestamp": False, "mqtt.retained_message": False,
                           "mqtt.message_type": "String", "mqtt.message_type_fixed_length": "1024",
                           "mqtt.message_to_sent": "${ll_payload}"})
    script(pub_tree, "生成可追溯终端数据", f"""
int seq = (vars.get('ll_seq') ?: '0').toInteger() + 1
vars.put('ll_seq', seq.toString())
def rng = vars.getObject('ll_rng')
if (rng == null) {{ rng = new Random({v['data']['seed']}L + ctx.getThreadNum()); vars.putObject('ll_rng', rng) }}
def body = [schema_version: 1, run_id: vars.get('ll_run_id'), device_id: vars.get('device_id'),
    device_type: vars.get('device_type'), site: vars.get('site'), seq: seq,
    message_id: vars.get('ll_run_id') + ':' + vars.get('device_id') + ':' + seq,
    sent_at_ms: System.currentTimeMillis(), temperature_c: Math.round((20 + rng.nextDouble() * 15) * 100) / 100.0,
    padding: 'x' * {v['data']['padding_bytes']}]
if ({v['faults']['invalid_every']} > 0 && seq % Math.max(1, {v['faults']['invalid_every']}) == 0) {{ body.temperature_c = 'invalid' }}
vars.put('ll_payload', groovy.json.JsonOutput.toJson(body))
""", "JSR223PreProcessor")
    # A sampler error is explicit even when the transport process exits with code zero.
    assertion, _ = element(pub_tree, "ResponseAssertion", "AssertionGui", "MQTT 发布状态必须为 200",
                            {"Assertion.test_field": "Assertion.response_code", "Assertion.assume_success": False})
    ET.SubElement(assertion, "intProp", name="Assertion.test_type").text = "8"
    tests = ET.SubElement(assertion, "collectionProp", name="Asserion.test_strings")
    prop(tests, "200", "200")
    disconnect(terminals, "MQTT Disconnect")
    # A final non-measured sampler also runs when disconnect itself reports an error.
    script(terminals, "标记终端执行结束", """
props.put('ll.lastFinishNs', System.nanoTime())
props.get('ll.finished').incrementAndGet()
SampleResult.setIgnore()
""")
    teardown = group(main, "保留订阅探针证据", 1, 0, "PostThreadGroup")
    observer_path = json.dumps(str((output / "observer.json").resolve()))
    script(teardown, "保存消息观测计数", f"""
new File({observer_path}).setText(groovy.json.JsonOutput.toJson([
    received: props.get('ll.observed').get(), ready: props.get('ll.ready'),
    terminals_finished: props.get('ll.finished').get()]), 'UTF-8')
SampleResult.setIgnore()
""")
    ET.indent(root, space="  ")
    plan_path = output / "test-plan.jmx"
    ET.ElementTree(root).write(plan_path, encoding="UTF-8", xml_declaration=True)
    scenario.write(output / "scenario.json")
    return plan_path, devices
